import { db } from '@/lib/db'
import { setSetting } from '@/lib/settings'
import { revalidatePath } from 'next/cache'
import { getPengurusList } from '@/lib/pengurus-server'
import { generateJumatSchedule } from '@/lib/khotib-generator'
import type { JumatRow } from '@/app/admin/(dashboard)/sections/jumat-items'

/**
 * Menyimpan jadwal khotib ke Section 'jumat' (untuk frontend) dan Setting 'jumat.jadwal'.
 */
export async function applyJumatScheduleToFrontend(schedule: JumatRow[]): Promise<void> {
  const items = schedule.map((item) => ({
    tanggal: item.tanggal,
    khatib: item.khatib,
    imam: item.imam || '',
  }))

  // 1. Simpan ke Setting sebagai backup
  await setSetting('jumat.jadwal', items)

  // 2. Simpan ke Section `jumat`
  const existingSection = await db.section.findUnique({
    where: { key: 'jumat' },
  })

  if (existingSection) {
    const prevContent =
      existingSection.content && typeof existingSection.content === 'object'
        ? (existingSection.content as Record<string, unknown>)
        : {}

    const jumatField =
      prevContent.jumat && typeof prevContent.jumat === 'object'
        ? (prevContent.jumat as Record<string, unknown>)
        : {}

    await db.section.update({
      where: { key: 'jumat' },
      data: {
        content: {
          ...prevContent,
          jumat: {
            ...jumatField,
            items,
          },
        },
      },
    })
  } else {
    await db.section.create({
      data: {
        key: 'jumat',
        title: 'Jadwal Khotib Sholat Jumat',
        content: {
          jumat: {
            items,
          },
        },
        isVisible: true,
        order: 4,
      },
    })
  }

  try {
    revalidatePath('/')
    revalidatePath('/kegiatan')
    revalidatePath('/admin/sections')
    revalidatePath('/admin/pengaturan/pengurus')
  } catch {
    // Ignore cache error in non-request contexts
  }
}

/**
 * Menghasilkan fallback jadwal khotib otomatis jika section kosong atau kadaluarsa.
 */
export async function getAutoGeneratedFallbackJumatSchedule(): Promise<JumatRow[]> {
  const pengurus = await getPengurusList()
  const khotibCandidates = pengurus
    .filter((p) => p.isActive && p.isKhotib)
    .map((p) => p.nama)

  const pool =
    khotibCandidates.length > 0
      ? khotibCandidates
      : [
          'Ust. Abdul Ghofur, Lc.',
          'Ust. M. Ridwan, S.Ag.',
          'H. Ahmad Subagio, M.Pd.',
          'Ust. Syahrul Ramadhan',
        ]

  const imamCandidates = pengurus
    .filter((p) => p.isActive && p.isImam)
    .map((p) => p.nama)

  return generateJumatSchedule({
    countWeeks: 4,
    khotibList: pool,
    imamList: imamCandidates.length > 0 ? imamCandidates : pool,
  })
}

