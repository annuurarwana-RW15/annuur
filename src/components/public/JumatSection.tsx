import type { Section } from '@prisma/client'
import { readField } from '@/app/admin/(dashboard)/sections/section-content'
import { jumatItems } from './content'
import { SectionHeading } from './SectionHeading'
import { getAutoGeneratedFallbackJumatSchedule } from '@/lib/khotib-server'
import type { JumatRow } from '@/app/admin/(dashboard)/sections/jumat-items'
import { JumatScheduleClient } from './JumatScheduleClient'

export async function JumatSection({ section }: { section: Section }) {
  const rawItems = jumatItems(readField(section.content, 'jumat', 'items'))

  // Filter tanggal yang aktif (hari ini atau mendatang)
  const todayIso = new Date().toISOString().slice(0, 10)
  const upcomingItems = rawItems.filter((item) => item.tanggal >= todayIso)

  // Jika belum diatur manual atau semua tanggal sudah lewat, auto-generate jadwal khotib
  let displayItems: JumatRow[] = upcomingItems
  let isAutoGenerated = false

  if (displayItems.length === 0) {
    displayItems = await getAutoGeneratedFallbackJumatSchedule()
    isAutoGenerated = true
  }

  return (
    <section id="jumat" aria-labelledby="jumat-judul" className="bg-krem">
      <div className="mx-auto max-w-6xl px-4 py-14">
        <div className="flex flex-col sm:flex-row sm:items-end sm:justify-between gap-3">
          <div>
            <SectionHeading id="jumat-judul">{section.title}</SectionHeading>
            <p className="mt-2 text-sm text-hijau-tua/80">
              Jadwal pelaksanaan ibadah sholat Jumat, khutbah, dan imam di Masjid An-nuur Arwana.
            </p>
          </div>
          {isAutoGenerated && (
            <span className="self-start sm:self-auto rounded-full bg-emerald-100 border border-emerald-300 px-3 py-1 text-xs font-semibold text-emerald-800">
              ✨ Jadwal Rutin Terjadwal
            </span>
          )}
        </div>

        <JumatScheduleClient items={displayItems} />
      </div>
    </section>
  )
}
